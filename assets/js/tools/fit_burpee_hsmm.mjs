// Refits the burpee HSMM by Viterbi training and prints the model module.
//
//   node assets/js/tools/fit_burpee_hsmm.mjs [--iterations N] FILE_OR_DIR... \
//     > assets/js/hooks/pose_burpee_hsmm_model.mjs
//
// Each pass segments every trace with the current model, keeps the traces whose count
// equals their known reps, and refits emissions, phase durations and the standing branch
// from that segmentation. Structure (minTicks, lag, outlier) is kept. Self-training can
// drift (a phase's deviation collapses), so a pass is kept only when at least as many traces
// count exactly as before it.

import { pathToFileURL } from "node:url";
import {
	BURPEE_HSMM_FEATURES,
	PHASES,
	segmentBurpeeHsmm,
	usableBurpeeHsmmFrame,
} from "../hooks/pose_burpee_hsmm.mjs";
import { BURPEE_HSMM_MODEL } from "../hooks/pose_burpee_hsmm_model.mjs";
import { loadTraceFile, traceFilesIn } from "./pose_trace_file.mjs";

// Deviations never shrink below these, so one tidy session cannot make the model brittle.
const SD_FLOOR = Object.freeze([0.05, 0.05, 0.03, 0.05, 0.2, 0.2]);
const MAX_LEAVE = 0.95;

export function fitBurpeeHsmm(model, traces) {
	const segmented = traces
		.map((trace) => ({ trace, ...segmentBurpeeHsmm(trace.frames, model) }))
		.filter(({ trace, reps }) => reps.length === trace.reps);

	if (segmented.length === 0) {
		throw new Error("no trace decodes to its known reps; nothing to fit from");
	}

	const labeled = segmented.flatMap(({ trace, phases }) =>
		labelFrames(trace.frames, phases, model.tickMs),
	);
	const runs = segmented.flatMap(({ phases }) => phaseRuns(phases));

	const emissions = Object.fromEntries(
		PHASES.map((phase) => [
			phase,
			fitEmission(
				labeled.filter((entry) => entry.phase === phase).map((entry) => entry.frame),
				model.emissions[phase],
			),
		]),
	);
	const leave = Object.fromEntries(
		PHASES.map((phase) => {
			const lengths = runs.filter((run) => run.phase === phase).map((run) => run.ticks);
			if (lengths.length === 0) return [phase, model.leave[phase]];
			const extra = Math.max(0.5, mean(lengths) - model.minTicks[phase] + 1);
			return [phase, Math.min(MAX_LEAVE, 1 / extra)];
		}),
	);
	const afterStanding = runs
		.slice(1)
		.filter((_, index) => runs[index].phase === "standing")
		.map((run) => run.phase);
	const toLowering = afterStanding.filter((phase) => phase === "lowering").length;
	const toOther = afterStanding.filter((phase) => phase === "other").length;
	const branch =
		toLowering + toOther > 0
			? {
					standing: {
						lowering: toLowering / (toLowering + toOther),
						other: toOther / (toLowering + toOther),
					},
				}
			: model.branch;

	return {
		model: { ...model, emissions, leave, branch },
		used: segmented.map(({ trace }) => trace.path),
		skipped: traces.length - segmented.length,
	};
}

export function exactCount(model, traces) {
	return traces.filter(
		(trace) => segmentBurpeeHsmm(trace.frames, model).reps.length === trace.reps,
	).length;
}

export function formatModel(model) {
	const round = (value) => Math.round(value * 1e4) / 1e4;
	const emissions = PHASES.map(
		(phase) =>
			`\t\t${phase}: {\n\t\t\tmean: [${model.emissions[phase].mean.map(round).join(", ")}],\n\t\t\tsd: [${model.emissions[phase].sd.map(round).join(", ")}],\n\t\t},`,
	).join("\n");
	const record = (values) =>
		PHASES.filter((phase) => values[phase] !== undefined)
			.map((phase) => `${phase}: ${round(values[phase])}`)
			.join(", ");

	return `// Generated by assets/js/tools/fit_burpee_hsmm.mjs; refit rather than edit by hand.
// Features, in order: ${BURPEE_HSMM_FEATURES.join(", ")}.
export const BURPEE_HSMM_MODEL = Object.freeze({
	tickMs: ${model.tickMs},
	lagTicks: ${model.lagTicks},
	minTicks: { ${record(model.minTicks)} },
	leave: { ${record(model.leave)} },
	branch: { standing: { ${Object.entries(model.branch.standing)
		.map(([phase, value]) => `${phase}: ${round(value)}`)
		.join(", ")} } },
	outlierWeight: ${model.outlierWeight},
	outlierLogDensity: ${round(model.outlierLogDensity)},
	emissions: {
${emissions}
	},
});
`;
}

function labelFrames(frames, phases, tickMs) {
	const byTick = new Map(phases.map((entry) => [entry.tMs / tickMs, entry.phase]));
	return frames
		.filter(usableBurpeeHsmmFrame)
		.map((frame) => ({ frame, phase: byTick.get(Math.floor(frame.tMs / tickMs)) }));
}

function phaseRuns(phases) {
	const runs = [];
	for (const { phase } of phases) {
		const last = runs.at(-1);
		if (last?.phase === phase) last.ticks += 1;
		else runs.push({ phase, ticks: 1 });
	}
	return runs;
}

function fitEmission(frames, previous) {
	if (frames.length === 0) return previous;
	const means = BURPEE_HSMM_FEATURES.map((name) => mean(frames.map((frame) => frame[name])));
	const sds = BURPEE_HSMM_FEATURES.map((name, index) =>
		Math.max(
			SD_FLOOR[index],
			Math.sqrt(mean(frames.map((frame) => (frame[name] - means[index]) ** 2))),
		),
	);
	return { mean: means, sd: sds };
}

function mean(values) {
	return values.reduce((sum, value) => sum + value, 0) / values.length;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
	const args = process.argv.slice(2);
	const iterationsAt = args.indexOf("--iterations");
	const iterations = iterationsAt >= 0 ? Number(args.splice(iterationsAt, 2)[1]) : 3;
	const traces = traceFilesIn(args).map(loadTraceFile).filter((trace) => Number.isInteger(trace.reps));

	let model = BURPEE_HSMM_MODEL;
	let exact = exactCount(model, traces);
	console.error(`current model: ${exact} of ${traces.length} traces count exactly`);
	for (let pass = 0; pass < iterations; pass++) {
		const fitted = fitBurpeeHsmm(model, traces);
		const fittedExact = exactCount(fitted.model, traces);
		console.error(
			`pass ${pass + 1}: fitted from ${fitted.used.length} traces; ${fittedExact} count exactly`,
		);
		if (fittedExact < exact) {
			console.error("pass rejected; keeping the previous model");
			break;
		}
		model = fitted.model;
		exact = fittedExact;
	}
	process.stdout.write(formatModel(model));
}
